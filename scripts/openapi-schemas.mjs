// Generates JSON Schemas for every REST route's request body, query object and response, straight
// from the TypeScript types the controllers already declare or infer. No swagger decorators:
//
//   1. Read the controllers (TypeScript AST) and write api/src/api/openapi/route-types.generated.ts,
//      one exported alias per route part, e.g.
//        export type CreditsController_earn_Body = Parameters<CreditsController['earn']>[1];
//        export type CreditsController_earn_Response = Awaited<ReturnType<CreditsController['earn']>>;
//      `npm run typecheck` then fails if a controller changes shape without regenerating.
//   2. Resolve those aliases with the TypeScript type checker (typescript-json-schema), so inferred
//      service return types are described too, and write
//      api/src/api/openapi/route-schemas.generated.ts, which openapi.document.ts attaches by operationId.
//
// `--check` fails instead of writing when either generated file is out of date (CI).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { URL, fileURLToPath } from 'node:url';
import ts from 'typescript';
import TJS from 'typescript-json-schema';

const root = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const restDir = root('api/src/api/rest');
const typesFile = root('api/src/api/openapi/route-types.generated.ts');
const schemasFile = root('api/src/api/openapi/route-schemas.generated.ts');
const check = process.argv.includes('--check');

const HTTP_DECORATORS = new Set(['Get', 'Post', 'Put', 'Patch', 'Delete']);
const decoratorsOf = (node) => (ts.canHaveDecorators(node) ? (ts.getDecorators(node) ?? []) : []);
const decoratorName = (d) =>
  ts.isCallExpression(d.expression) ? d.expression.expression.getText() : d.expression.getText();
const firstStringArg = (d) => {
  const arg = ts.isCallExpression(d.expression) ? d.expression.arguments[0] : undefined;
  return arg && ts.isStringLiteralLike(arg) ? arg.text : undefined;
};

/** @type {{ file: string; controller: string; method: string; parts: { name: string; type: string }[] }[]} */
const routes = [];
for (const fileName of readdirSync(restDir)
  .filter((f) => f.endsWith('.controller.ts'))
  .sort()) {
  const source = ts.createSourceFile(
    fileName,
    readFileSync(`${restDir}/${fileName}`, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );
  for (const statement of source.statements) {
    if (!ts.isClassDeclaration(statement) || !statement.name) continue;
    if (!decoratorsOf(statement).some((d) => decoratorName(d) === 'Controller')) continue;
    const controller = statement.name.text;
    for (const member of statement.members) {
      if (!ts.isMethodDeclaration(member) || !ts.isIdentifier(member.name)) continue;
      if (!decoratorsOf(member).some((d) => HTTP_DECORATORS.has(decoratorName(d)))) continue;
      const method = member.name.text;
      const params = `Parameters<${controller}['${method}']>`;
      const parts = [{ name: 'Response', type: `Awaited<ReturnType<${controller}['${method}']>>` }];
      const bodyFields = [];
      const queryFields = [];
      member.parameters.forEach((param, index) => {
        // `limit?: string` or `limit = 50`: the caller may leave it out.
        const optional = param.questionToken || param.initializer ? '?' : '';
        const field = (key) => `${JSON.stringify(key)}${optional}: ${params}[${index}]`;
        for (const d of decoratorsOf(param)) {
          const name = decoratorName(d);
          const key = firstStringArg(d);
          if (name === 'Body' && key === undefined) parts.push({ name: 'Body', type: `${params}[${index}]` });
          else if (name === 'Body') bodyFields.push(field(key));
          else if (name === 'Query' && key === undefined) parts.push({ name: 'Query', type: `${params}[${index}]` });
          else if (name === 'Query') queryFields.push(field(key));
        }
      });
      if (bodyFields.length) parts.push({ name: 'Body', type: `{ ${bodyFields.join('; ')} }` });
      if (queryFields.length) {
        if (parts.some((p) => p.name === 'Query')) {
          throw new Error(`${controller}.${method} mixes @Query() and @Query('key'); use one of them`);
        }
        parts.push({ name: 'Query', type: `{ ${queryFields.join('; ')} }` });
      }
      routes.push({ file: fileName.replace(/\.ts$/, '.js'), controller, method, parts });
    }
  }
}

const imports = new Map();
for (const r of routes) imports.set(r.file, (imports.get(r.file) ?? new Set()).add(r.controller));
const typesSource = [
  '// Generated by `npm run openapi:schemas` from api/src/api/rest/*.controller.ts. Do not edit.',
  // Relative, not `#api/…`: that subpath resolves to dist/, and the schemas must follow the source.
  ...[...imports].map(([file, names]) => `import type { ${[...names].sort().join(', ')} } from '../rest/${file}';`),
  '',
  ...routes.flatMap((r) => r.parts.map((p) => `export type ${r.controller}_${r.method}_${p.name} = ${p.type};`)),
  '',
].join('\n');

// The generator reads the alias file through the real tsconfig, so it must exist on disk first.
const previousTypes = safeRead(typesFile);
writeFileSync(typesFile, typesSource);
let schemasSource;
try {
  const program = TJS.programFromConfig(root('api/tsconfig.json'));
  const generator = TJS.buildGenerator(
    program,
    {
      required: true,
      ref: true,
      aliasRef: false,
      topRef: false,
      noExtraProps: false,
      strictNullChecks: true,
      ignoreErrors: true,
      validationKeywords: [],
    },
    [typesFile],
  );
  if (!generator) throw new Error('typescript-json-schema could not build a generator');
  const names = routes.flatMap((r) => r.parts.map((p) => `${r.controller}_${r.method}_${p.name}`));
  const definitions = generator.getSchemaForSymbols(names).definitions ?? {};
  // `Record<string,unknown>` and friends come back URI-encoded; give every definition a plain name.
  // Types read from a package's .d.ts come back as `import("/abs/path/dist/x", …).Name`: keep `Name`.
  const rename = (name) => {
    const decoded = decodeURIComponent(name);
    const imported = /^import\(.*\)\.([A-Za-z0-9_]+)$/.exec(decoded);
    return (imported ? imported[1] : decoded).replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  };
  const sorted = {};
  for (const key of Object.keys(definitions).sort()) {
    const name = rename(key);
    if (name in sorted) throw new Error(`Two schemas would both be named ${name}`);
    sorted[name] = definitions[key];
  }
  const json = JSON.stringify(sorted, null, 2).replace(
    /"#\/definitions\/([^"]+)"/g,
    (_, name) => `"#/components/schemas/${rename(name)}"`,
  );
  schemasSource = [
    '// Generated by `npm run openapi:schemas` from route-types.generated.ts. Do not edit.',
    `export const ROUTE_SCHEMAS: Record<string, Record<string, unknown>> = ${json};`,
    '',
  ].join('\n');
} finally {
  if (check) writeFileSync(typesFile, previousTypes);
}

if (check) {
  const stale = [];
  if (previousTypes !== typesSource) stale.push('route-types.generated.ts');
  if (safeRead(schemasFile) !== schemasSource) stale.push('route-schemas.generated.ts');
  if (stale.length) {
    console.error(`${stale.join(' and ')} out of date. Run \`npm run openapi:schemas\` and commit the result.`);
    process.exit(1);
  }
  console.log(`Route schemas are up to date (${routes.length} routes).`);
} else {
  writeFileSync(schemasFile, schemasSource);
  console.log(`Wrote route types and schemas for ${routes.length} routes.`);
}

function safeRead(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}
